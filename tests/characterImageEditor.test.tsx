import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, expect, it, vi } from 'vitest';
import { CharacterImageEditor, ConceptImageEditor } from '../src/steps/characters/CharacterImageEditor';
import { createProject } from '../src/state/schema';
import { newCharacter } from '../src/characters/commands';
import { useProjectStore } from '../src/state/store';
import { IMAGE_PREFERENCES_SETTING } from '../src/images/ConceptImageEditor';
import { API_KEY_SETTING } from '../src/ai/openai';
import { getBlob, getSetting, setSetting } from '../src/storage/db';

(globalThis as Record<string, unknown>).IS_REACT_ACT_ENVIRONMENT = true;
let host: HTMLDivElement;
let root: ReturnType<typeof createRoot>;
afterEach(async () => {
  if (root) await act(async () => root.unmount());
  host?.remove(); vi.restoreAllMocks(); vi.unstubAllGlobals();
  await useProjectStore.getState().close();
});
it.each(['character', 'stage', 'prop', 'shot'] as const)('opens an accessible %s editor and saves only on Use image', async (kind) => {
  Object.defineProperty(HTMLDialogElement.prototype, 'showModal', { configurable: true, value: function (this: HTMLDialogElement) { this.setAttribute('open', ''); } });
  vi.stubGlobal('URL', { createObjectURL: vi.fn(() => 'blob:test'), revokeObjectURL: vi.fn() });
  vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify({data:[{b64_json:'AQID'}]}))));
  const viewport = Object.assign(new EventTarget(), { height: 844, offsetTop: 0 });
  vi.stubGlobal('visualViewport', viewport);
  await setSetting(API_KEY_SETTING, 'test-key');
  await setSetting(IMAGE_PREFERENCES_SETTING, {model:'gpt-image-2.5-sunburst',quality:'high'});
  const p = createProject('Image UI'); p.characters.push(newCharacter('Ben', [], 'ben'));
  p.stages.push({id: 'stage', name: 'Cafe', sceneLineIds: [], objects: []});
  p.props.push({id: 'prop', name: 'Mug', source: {kind:'library', item:'mug'}, defaultScale:1});
  p.shots.push({id:'shot',number:'1.1',lineIds:['line']});
  const reference = new Blob(['snapshot'], {type:'image/png'});
  useProjectStore.getState().open(p);
  host=document.createElement('div'); document.body.append(host); root=createRoot(host);
  const onClose=vi.fn();
  await act(async () => root.render(<MemoryRouter>{kind === 'character' ? <CharacterImageEditor character={p.characters[0]} onClose={onClose} /> : <ConceptImageEditor subject={kind === 'shot' ? {id:'shot',name:'Shot 1.1'} : kind === 'prop' ? p.props[0] : p.stages[0]} kind={kind} defaultPrompt={kind === 'shot' ? '' : kind === 'prop' ? 'Blue mug' : 'Warm cafe'} buildPrompt={kind === 'shot' ? (extra) => `Shot composition. ${extra}` : undefined} imageContext={kind === 'shot' ? {frameProgress:0.5,aspect:9/16} : undefined} reference={reference} onClose={onClose} />}</MemoryRouter>));
  await vi.waitFor(async () => { await act(async () => { await new Promise(resolve => setTimeout(resolve, 10)); }); expect(document.querySelector('select')?.value).toBe('gpt-image-2.5-sunburst'); });
  const dialog=document.querySelector('dialog')!;
  const selects = dialog.querySelectorAll('select');
  expect(selects[1].value).toBe('high');
  expect(dialog.textContent).toContain('Estimated');
  const generated = dialog.querySelector('details');
  if (kind === 'shot') {
    expect(generated?.open).toBe(false);
    expect(generated?.querySelector('summary')?.textContent).toBe('Generated prompt');
    expect(generated?.querySelector('pre')?.textContent).toBe('Shot composition. ');
    expect(generated?.nextElementSibling?.textContent).toContain('Additional prompt');
    await act(async () => { generated!.open = true; generated!.dispatchEvent(new Event('toggle')); });
    expect(generated?.open).toBe(true);
  } else expect(generated).toBeNull();
  if (kind !== 'character') expect(dialog.textContent).toContain('billed additionally');
  await act(async () => { selects[0].value='gpt-image-1-mini'; selects[0].dispatchEvent(new Event('change',{bubbles:true})); });
  expect(await getSetting(IMAGE_PREFERENCES_SETTING)).toEqual({model:'gpt-image-1-mini',quality:'high'});
  expect(dialog.open).toBe(true);
  expect(dialog.getAttribute('aria-labelledby')).toBe('character-image-title');
  const button=(text:string)=>[...dialog.querySelectorAll('button')].find(b=>b.textContent===text)!;
  const input = dialog.querySelector('textarea')!;
  const originalPrompt = input.value;
  await act(async () => input.focus());
  expect(dialog.classList.contains('editing-prompt')).toBe(true);
  viewport.height = 420; viewport.offsetTop = 32;
  await act(async () => viewport.dispatchEvent(new Event('resize')));
  expect(dialog.style.getPropertyValue('--image-editor-height')).toBe('420px');
  expect(dialog.style.getPropertyValue('--image-editor-top')).toBe('32px');
  await act(async () => button('Done').click());
  expect(dialog.classList.contains('editing-prompt')).toBe(false);
  expect(input.value).toBe(originalPrompt);
  expect(document.activeElement).not.toBe(input);
  await act(async () => button('Generate image').click());
  expect(dialog.querySelector('img')?.getAttribute('src')).toBe('blob:test');
  const preview = document.querySelector('.image-preview-dialog') as HTMLDialogElement;
  expect(preview.open).toBe(true);
  expect(preview.querySelector('img')?.getAttribute('src')).toBe('blob:test');
  // A fresh render offers Discard and Use instead of Close.
  expect([...preview.querySelectorAll('header button')].map((b) => b.textContent)).toEqual(['Download', 'Discard', 'Use']);
  await act(async () => preview.querySelector<HTMLButtonElement>('[aria-label="Discard this image"]')!.click());
  expect(document.querySelector('.image-preview-dialog')).toBeNull();
  expect(dialog.open).toBe(true);
  expect([...dialog.querySelectorAll('button')].some((b) => b.textContent === 'Use image')).toBe(false);
  expect(useProjectStore.getState().project![kind === 'shot' ? 'shots' : kind === 'stage' ? 'stages' : kind === 'prop' ? 'props' : 'characters'][0].image).toBeUndefined();
  await act(async () => button('Generate image').click());
  await act(async () => { document.querySelector<HTMLButtonElement>('.image-preview-dialog [aria-label="Use this image"]')!.click(); await vi.waitFor(() => expect(onClose).toHaveBeenCalledOnce()); });
  expect(document.querySelector('.image-preview-dialog')).toBeNull();
  const image=useProjectStore.getState().project![kind === 'shot' ? 'shots' : kind === 'stage' ? 'stages' : kind === 'prop' ? 'props' : 'characters'][0].image!;
  expect(image.prompt).toContain(kind === 'shot' ? 'Shot composition.' : kind === 'stage' ? 'Warm cafe' : kind === 'prop' ? 'Blue mug' : 'Ben');
  if (kind === 'shot') { expect(image.frameProgress).toBe(0.5); expect(image.aspect).toBe(9/16); expect(image.additionalPrompt).toBe(''); }
  if (kind !== 'character') expect(await getBlob(image.guidanceBlob!)).toBeDefined();
  expect(await getBlob(image.blob)).toBeDefined();
  expect(onClose).toHaveBeenCalledOnce();
  if (kind === 'prop') {
    const saved = useProjectStore.getState().project!.props[0];
    await act(async () => root.render(<MemoryRouter><ConceptImageEditor key="reopened" subject={saved} kind="prop" defaultPrompt="A different default" reference={reference} onClose={onClose} /></MemoryRouter>));
    expect(document.querySelector('textarea')!.value).toBe('Blue mug');
    await vi.waitFor(async () => { await act(async () => { await new Promise(resolve => setTimeout(resolve, 10)); }); expect(document.querySelector('select')?.value).toBe('gpt-image-1-mini'); });
  }
});
